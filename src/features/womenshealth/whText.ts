export const WH_TEXT: Record<WhLang, Table> = { en: EN, fr: FR, pidgin: PIDGIN, ar: AR, ff: FF };

/** One sentence in the given language; {n}, {name}... are filled from vars. */
export function wt(lang: WhLang, key: WhKey, vars?: Record<string, string | number>): string {
  const table = WH_TEXT[lang] || EN;
  let s: string = table[key] || EN[key] || String(key);
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

/** The server's reason ("bad_name", "phone_in_text"...) as a sentence. */
export function whReason(lang: WhLang, reason: unknown): string {
  const key = ('e_' + String(reason || 'generic')) as WhKey;
  return key in EN ? wt(lang, key) : wt(lang, 'e_generic');
}

export type WhT = (key: WhKey, vars?: Record<string, string | number>) => string;

/** The language, its direction and a t() for the women's health pages; follows language changes. */
export function useWhText(): { lang: WhLang; dir: 'rtl' | 'ltr'; t: WhT } {
  const lang = normWhLang(useLang());
  return { lang, dir: whDir(lang), t: (key: WhKey, vars?: Record<string, string | number>) => wt(lang, key, vars) };
}

