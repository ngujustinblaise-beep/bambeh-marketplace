// ------------------------------------------------------------------ Cameroon time (UTC+1, no summer time)
export function doualaNow(d: Date = new Date()): { day: number; minutes: number; ymd: string } {
  const x = new Date(d.getTime() + 3600 * 1000);
  return { day: x.getUTCDay(), minutes: x.getUTCHours() * 60 + x.getUTCMinutes(), ymd: x.toISOString().slice(0, 10) };
}

function toMinutes(hhmm: string | null | undefined): number | null {
  const m = /^([01]?[0-9]|2[0-3]):([0-5][0-9])/.exec(String(hhmm || ''));
  return m ? Number(m[1]) * 60 + Number(m[2]) : null;
}

/** Open day and night, open now, closed now, or unknown when no hours were given (handles hours past midnight). */
export function placeOpenState(p: { open_24h: boolean; open_days: readonly number[] | null; opens_at: string | null; closes_at: string | null },
                               now: Date = new Date()): 'open24' | 'open' | 'closed' | 'unknown' {
  if (p.open_24h) return 'open24';
  const o = toMinutes(p.opens_at);
  const c = toMinutes(p.closes_at);
  if (o === null || c === null) return 'unknown';
  const list = Array.isArray(p.open_days) && p.open_days.length ? p.open_days : [0, 1, 2, 3, 4, 5, 6];
  const { day, minutes } = doualaNow(now);
  const prev = (day + 6) % 7;
  if (c > o) return list.indexOf(day) >= 0 && minutes >= o && minutes < c ? 'open' : 'closed';
  if (list.indexOf(day) >= 0 && minutes >= o) return 'open';
  if (list.indexOf(prev) >= 0 && minutes < c) return 'open';
  return 'closed';
}

/** "17:00" when it opens later today, else null. */
export function opensLaterToday(p: { open_days: readonly number[] | null; opens_at: string | null }, now: Date = new Date()): string | null {
  const o = toMinutes(p.opens_at);
  if (o === null) return null;
  const list = Array.isArray(p.open_days) && p.open_days.length ? p.open_days : [0, 1, 2, 3, 4, 5, 6];
  const { day, minutes } = doualaNow(now);
  return list.indexOf(day) >= 0 && minutes < o ? String(p.opens_at).slice(0, 5) : null;
}

/** "Mon, Tue, Wed..." in week order starting Monday, or "Every day". */
export function daysText(lang: WhLang, days: readonly number[] | null | undefined): string {
  const list = Array.isArray(days) ? days : [];
  if (list.length === 0 || list.length === 7) return wt(lang, 'everyDay');
  return [1, 2, 3, 4, 5, 6, 0].filter((d) => list.indexOf(d) >= 0).map((d) => wt(lang, ('d' + d) as WhKey)).join(', ');
}

function localeOf(lang: WhLang): string {
  return lang === 'fr' || lang === 'ff' ? 'fr-FR' : lang === 'ar' ? 'ar-u-nu-latn' : 'en-GB';
}

/** A calendar day ("2026-10-18") as "Sat 18 Oct". */
export function fmtDay(ymd: string | null | undefined, lang: WhLang): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(ymd || ''));
  if (!m) return '';
  const d = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 12));
  try {
    return d.toLocaleDateString(localeOf(lang), { weekday: 'short', day: 'numeric', month: 'short', timeZone: 'UTC' });
  } catch {
    return m[3] + '/' + m[2];
  }
}

/** A calendar day as "18 Oct 2026". */
export function fmtLongDay(ymd: string | null | undefined, lang: WhLang): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(ymd || ''));
  if (!m) return '';
  const d = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3]), 12));
  try {
    return d.toLocaleDateString(localeOf(lang), { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
  } catch {
    return m[3] + '/' + m[2] + '/' + m[1];
  }
}

/** When something was saved on this phone, Cameroon time: "11 Oct 2026, 21:40". */
export function fmtSavedAt(iso: string | null | undefined, lang: WhLang): string {
  const d = new Date(String(iso || ''));
  if (isNaN(d.getTime())) return '';
  try {
    return d.toLocaleString(localeOf(lang), { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
                                              timeZone: 'Africa/Douala' });
  } catch {
    return new Date(d.getTime() + 3600 * 1000).toISOString().slice(0, 16).replace('T', ' ');
  }
}

/** "Sat 18 Oct" or "Sat 18 Oct - Mon 20 Oct". */
export function dayRange(lang: WhLang, starts: string, ends: string): string {
  return starts === ends || !ends ? fmtDay(starts, lang) : fmtDay(starts, lang) + ' - ' + fmtDay(ends, lang);
}

/** Today, tomorrow, already going on, or null (later). today = Cameroon "YYYY-MM-DD". */
export function dayWhen(starts: string, ends: string, today: string = doualaNow().ymd): 'today' | 'tomorrow' | 'on' | 'ended' | null {
  if (ends && ends < today) return 'ended';
  if (starts === today) return 'today';
  if (starts < today) return 'on';
  const t = new Date(today + 'T12:00:00Z');
  t.setUTCDate(t.getUTCDate() + 1);
  return starts === t.toISOString().slice(0, 10) ? 'tomorrow' : null;
}

// ------------------------------------------------------------------ phone numbers
/** Same rule as the database: 9 digits (6... mobile, 2... fixed line), "+237" or "00237" taken off. null = empty, '!' = not a number. */
export function phoneDigits(raw: string | null | undefined): string | null {
  const v = String(raw || '').trim();
  if (!v) return null;
  let d = v.replace(/[^0-9]/g, '');
  if (d.indexOf('00237') === 0) d = d.slice(5);
  else if (d.indexOf('237') === 0 && d.length === 12) d = d.slice(3);
  return /^[26][0-9]{8}$/.test(d) ? d : '!';
}

/** "677123456" as "6 77 12 34 56" (fixed lines "2 22 31 00 01"). */
export function fmtPhone(d: string): string {
  return /^[0-9]{9}$/.test(d) ? d[0] + ' ' + d.slice(1, 3) + ' ' + d.slice(3, 5) + ' ' + d.slice(5, 7) + ' ' + d.slice(7, 9) : d;
}

export function telHref(d: string): string {
  return 'tel:+237' + d;
}

/** Same rule as the database: a Cameroon phone number or a WhatsApp / Telegram link inside a text. */
export function hasPhoneNumber(text: string | null | undefined): boolean {
  const v = String(text || '');
  if (/(wa\.me|whatsapp\.com|t\.me\/|chat\.whatsapp)/i.test(v)) return true;
  const joined = v.replace(/([0-9])[\s.()\/-]+(?=[0-9+])/g, '$1');
  return /(^|[^0-9])(\+?237|00237)?[26][0-9]{8}([^0-9]|$)/.test(joined);
}

