/**
 * Which language to show the guide in. A language nobody checked is never shown to women: the reader gets
 * the first checked language from her own list (Fulfulde and Arabic readers: French, then English; Pidgin:
 * English, then French). Staff previews always use the app language.
 */
export function guideLangFor(appLang: WhLang, langs: readonly string[]): { show: WhLang | null; fallback: boolean } {
  const on = (l: WhLang) => langs.indexOf(l) >= 0;
  if (on(appLang)) return { show: appLang, fallback: false };
  const order: Record<WhLang, WhLang[]> = {
    en: ['fr', 'pidgin'], fr: ['en'], pidgin: ['en', 'fr'], ar: ['fr', 'en'], ff: ['fr', 'en'],
  };
  for (const l of order[appLang]) if (on(l)) return { show: l, fallback: true };
  for (const l of WH_LANGS) if (on(l)) return { show: l, fallback: true };
  return { show: null, fallback: false };
}

