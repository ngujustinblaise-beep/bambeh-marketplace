const LOCALES: Record<ShopLang, string> = { en: 'en-GB', fr: 'fr-FR', pidgin: 'en-GB', ar: 'ar', ff: 'fr-FR' };

/** "March 2026" (month) or "25 November 2026" (day) in the reader's language; '' when the date cannot be read. */
export function shopDate(iso: unknown, lang: ShopLang, withDay = false): string {
  const d = new Date(String(iso ?? ''));
  if (Number.isNaN(d.getTime())) return '';
  try {
    return d.toLocaleDateString(LOCALES[lang], withDay
      ? { day: 'numeric', month: 'long', year: 'numeric', numberingSystem: 'latn' } as Intl.DateTimeFormatOptions
      : { month: 'long', year: 'numeric', numberingSystem: 'latn' } as Intl.DateTimeFormatOptions);
  } catch {
    return d.toISOString().slice(0, 10);
  }
}

/** The reason the database gave, as the text key to show. */
export function reasonKey(reason: unknown): ShopKey {
  const r = String(reason ?? '');
  if (r === 'bad_slug' || r === 'reserved' || r === 'business' || r === 'taken' || r === 'too_soon' || r === 'too_many_links'
      || r === 'name_too_short' || r === 'name_too_long' || r === 'name_reserved_word' || r === 'town_too_long'
      || r === 'account_off' || r === 'sign_in') return ('r_' + r) as ShopKey;
  if (r === 'no_numbers' || r === 'name_no_numbers' || r === 'town_no_numbers') return 'r_no_numbers'; // a number in the link too
  if (r === 'no_contacts' || r === 'name_no_contacts' || r === 'town_no_contacts') return 'r_no_contacts';
  if (r === 'name_bad_text' || r === 'town_bad_text') return 'r_bad_text';
  return 'r_failed';
}
