export function zermLang(raw: unknown): ZermLang {
  const v = String(raw ?? 'en').toLowerCase();
  if (v === 'fr' || v.indexOf('fr-') === 0) return 'fr';
  if (v === 'pidgin' || v === 'pcm') return 'pidgin';
  if (v === 'ar' || v.indexOf('ar-') === 0) return 'ar';
  if (v === 'ff' || v === 'ful' || v === 'fulfulde') return 'ff';
  return 'en';
}

export function zermFill(s: string, vals: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vals ? String(vals[k]) : m));
}

/** Coins are counted in ten-thousandths (a reward is 0.0025): show up to four decimals. */
export function fmtCoins(n: unknown): string {
  const v = Number(n) || 0;
  return v.toLocaleString(undefined, { maximumFractionDigits: 4 });
}

/** "1 coin" / "2.5 coins" in the reader's language. */
export function coinsLabel(t: Record<ZermKey, string>, n: unknown): string {
  const v = Number(n) || 0;
  return v === 1 ? t.coinOne : zermFill(t.coinMany, { n: fmtCoins(v) });
}
