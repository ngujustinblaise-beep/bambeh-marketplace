// ─── Initialize i18n ──────────────────────────────────────────────────────────
const initI18n = () => {
  const lng = getStoredLanguage();

  i18n.use(initReactI18next).init({
    lng,
    fallbackLng: FALLBACK_LANGUAGE,
    defaultNS: "common",
    resources: {
      fr: { common: fr.common, auth: fr.auth, marketplace: fr.marketplace, jobs: fr.jobs, vendor: fr.vendor, payment: fr.payment, errors: fr.errors },
      en: { common: en.common, auth: en.auth, marketplace: en.marketplace, jobs: en.jobs, vendor: en.vendor, payment: en.payment, errors: en.errors },
    },
    interpolation: {
      escapeValue: false,
    },
    react: {
      useSuspense: false,
    },
    debug: import.meta.env.DEV,
  });

  return i18n;
};

export default initI18n();

export { DEFAULT_LANGUAGE, FALLBACK_LANGUAGE };
